import { rm, stat } from "node:fs/promises";
import { resolve } from "node:path";
import { build } from "esbuild";

/**
 * Produces the production entrypoint.
 *
 * Every workspace package sets `noEmit` and points its `exports` at raw TypeScript, so `tsc` alone
 * cannot produce something Node can run: the emitted JavaScript would still import `@dib/gamedata`,
 * which resolves to a `.ts` file at runtime. Bundling sidesteps that without forcing a
 * workspace-wide exports refactor, and it means the deployed image carries one file and no
 * transpiler.
 *
 * Type safety is not weakened by this: `pnpm typecheck` still runs `tsc --noEmit` over the same
 * sources, and the deployment pipeline runs it before this script.
 */

const packageRoot = import.meta.dirname;
const outfile = resolve(packageRoot, "dist/dib-game-server.mjs");

await rm(resolve(packageRoot, "dist"), { recursive: true, force: true });

const result = await build({
  entryPoints: [resolve(packageRoot, "src/cli.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  // Matches the `engines: node >=20.11` floor rather than the newer runtime in the image, so the
  // bundle stays runnable on the lowest version the workspace claims to support.
  target: "node20",
  // Workspace packages and `zod` are bundled; only Node's own builtins stay external. `node:` is
  // implied by platform: node, but stating it keeps the intent explicit if the platform changes.
  external: [],
  sourcemap: true,
  minify: false,
  legalComments: "inline",
  logLevel: "info",
  metafile: true,
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  banner: {
    js: [
      "// Dragon Island Blue authoritative game server - generated by apps/game-server/build.mjs.",
      "// Do not edit. Run `pnpm --filter @dib/game-server build` to regenerate.",
    ].join("\n"),
  },
});

if (result.errors.length > 0) process.exit(1);

const { size } = await stat(outfile);
process.stdout.write(
  `\nBundled ${outfile}\n` +
  `Size: ${(size / 1024).toFixed(1)} KiB\n` +
  `Run with: node ${outfile} serve\n`,
);
