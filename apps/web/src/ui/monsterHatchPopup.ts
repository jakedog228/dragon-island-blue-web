/** Shared dependencies supplied by every source `MonsterHatchPopup` caller. */
export interface MonsterHatchPopupEnvironment {
  readonly parent: Container;
  readonly assets: AssetLibrary;
  readonly scale9: Scale9SpritesData;
  readonly ticker: Ticker;
  readonly owner?: object;
  readonly zIndex?: number;
  readonly sfx?: PopupSfxHooks;
}

export type MonsterHatchPopupOptions = Omit<
  PopupOpts,
  "assets" | "scale9" | "ticker" | "overlays" | "dismissOnTap" | "owner" | "zIndex" | "sfx"
> & {
  /** Native `PopupConfig.hideOverlays`; false keeps ClerkGirl and TutorialRightSide. */
  readonly hideOverlays?: boolean;
};

/**
 * Source-family constructor policy shared by battle, world, startup, and dungeon dialogs.
 *
 * Content, buttons, animation flags, and geometry overrides remain explicit at each feature call
 * site. This helper only owns the behavior that comes from constructing a `MonsterHatchPopup`.
 */
export function monsterHatchPopupOptions(
  environment: MonsterHatchPopupEnvironment,
  options: MonsterHatchPopupOptions,
): PopupOpts {
  const { hideOverlays = false, ...specific } = options;
  return {
    assets: environment.assets,
    scale9: environment.scale9,
    ticker: environment.ticker,
    ...(hideOverlays ? {} : { overlays: MONSTER_HATCH_OVERLAYS }),
    dismissOnTap: false,
    ...(environment.owner === undefined ? {} : { owner: environment.owner }),
    ...(environment.zIndex === undefined ? {} : { zIndex: environment.zIndex }),
    ...(environment.sfx === undefined ? {} : { sfx: environment.sfx }),
    ...specific,
  };
}

export function showMonsterHatchPopup(
  environment: MonsterHatchPopupEnvironment,
  options: MonsterHatchPopupOptions,
): Promise<Popup> {
  return Popup.show(
    environment.parent,
    monsterHatchPopupOptions(environment, options),
  );
}


let MESSAGE_MIN_WIDTH = idiomPairPt(300, 600, DISPLAY_MODE);


let MESSAGE_FONT_SIZE = idiomPairPt(14, 28, DISPLAY_MODE);
registerRuntimeSettingsRefresh(() => {
  MESSAGE_MIN_WIDTH = idiomPairPt(300, 600, DISPLAY_MODE);
  MESSAGE_FONT_SIZE = idiomPairPt(14, 28, DISPLAY_MODE);
});

/** Shared body generated by `MonsterHatchPopup showPopupForLocalizedMessageName:`, plus the seam a
 *  caller needs to restate the message after `Popup.show` has already measured the card. */
export interface MonsterHatchMessageBlock {
  readonly root: Container;


  setText(text: string): void;
}

export function buildMonsterHatchMessageBlock(messageText: string): MonsterHatchMessageBlock {
  const root = new Container();
  const layout = popupTextLayout(MESSAGE_MIN_WIDTH, MESSAGE_FONT_SIZE, DISPLAY_MODE, (wrapWidth) => {
    const probe = makeTtfLabel(messageText, MESSAGE_FONT_SIZE, {
      wordWrapWidth: wrapWidth,
      align: "center",
      outline: false,
    });
    const measured = { width: probe.width, height: probe.height };
    probe.destroy();
    return measured;
  });
  const message = makeTtfLabel(messageText, MESSAGE_FONT_SIZE, {
    wordWrapWidth: layout.wrapWidth,
    align: "center",
    outline: false,
  });
  root.addChild(
    new Graphics()
      .rect(0, 0, layout.width, Math.max(1, layout.height))
      .fill({ color: 0x000000, alpha: 0 }),
  );
  const alignMessage = (): void => {
    // The dimensioned CCLabelTTF overload is horizontally centered by this configuration but
    // retains its default top vertical alignment; the recovered extra height sits below the ink.
    message.position.set((layout.width - message.width) / 2, 0);
  };
  alignMessage();
  root.addChild(message);
  return {
    root,
    setText(text: string): void {
      message.text = text;
      alignMessage();
    },
  };
}

/** Shared body generated by `MonsterHatchPopup showPopupForLocalizedMessageName:`. */
export function buildMonsterHatchMessageContent(messageText: string): Container {
  return buildMonsterHatchMessageBlock(messageText).root;
}

export function buildLocalizedMonsterHatchMessageContent(
  strings: LocalizedStrings,
  name: string,
): Container {
  return buildMonsterHatchMessageContent(
    localizedString(strings, `${name}MessageKey`),
  );
}
