export interface ModModuleCatalog {
  list(): readonly string[];
  has(id: string): boolean;
  load(id: string): Promise<unknown>;
}

const webModules = import.meta.glob([
  "../**/*.ts",
  "!../**/*.test.ts",
  "!../**/*.spec.ts",
  "!../debug/**",
]) as Record<string, () => Promise<unknown>>;
const loaders = new Map<string, () => Promise<unknown>>([
  ...Object.entries(webModules).map(([path, load]) => [
    // Vite normalizes matches in this directory to ./ even though the glob starts at ../.
    // Public module IDs are always relative to src, including these content siblings.
    path.startsWith("./") ? `web/content/${path.slice(2)}` : `web/${path.replace(/^\.\.\//, "")}`,
    load,
  ] as const),
  ["@dib/engine", () => import("@dib/engine")],
  ["@dib/gamedata/browser", () => import("@dib/gamedata/browser")],
  ["@dib/player-domain", () => import("@dib/player-domain")],
  ["@dib/renderer", () => import("@dib/renderer")],
  ["pixi.js", () => import("pixi.js")],
]);

const moduleIds = Object.freeze([...loaders.keys()].sort(compareText));

/**
 * Lazy access to the complete web source-module graph plus each public workspace runtime package.
 * This is intentionally generated by module discovery instead of a per-feature mod allowlist.
 */
export const fullTrustModModules: ModModuleCatalog = Object.freeze({
  list: () => moduleIds,
  has: (id: string) => loaders.has(id),
  load: async (id: string) => {
    const load = loaders.get(id);
    if (load === undefined) throw new Error(`Unknown runtime module ${JSON.stringify(id)}`);
    return await load();
  },
});

function compareText(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}
